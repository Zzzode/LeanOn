// AdaptiveIconDrawable shows the center 72dp of a 108dp layer. Map the
// measured heart to 80% of that visible area, not of the full layer. At this
// size, shift down 2.75dp to center the filled/contrast-weighted mass.
const scale = (72 * 0.8) / 1068;
const inset = 54 - 627 * scale;
const opticalOffset = 2.75;
const translateY = inset + opticalOffset;
const tileScale = (1254 * 0.8) / 1068;
const tileInset = 627 * (1 - tileScale);
const tileTranslateY = tileInset + opticalOffset * 1254 / 72;
const args = process.argv.slice(2);
assert(args.length === 0 || (args.length === 1 && args[0] === '--check'),
  'Usage: node scripts/generate-icons.mjs [--check]');

// Sample the canonical cubic silhouette against the 66dp safe-zone circle.
// Fail on new SVG commands rather than silently validating the wrong geometry.
let radius = 0;
for (const path of heart) {
  const tokens = path.match(/[A-Za-z]|-?\d+(?:\.\d+)?/g);
  let x = 0;
  let y = 0;
  for (let i = 0; i < tokens.length;) {
    const command = tokens[i++];
    if (command === 'M') {
      x = Number(tokens[i++]);
      y = Number(tokens[i++]);
    } else if (command === 'C') {
      const [x1, y1, x2, y2, x3, y3] = tokens.slice(i, i + 6).map(Number);
      i += 6;
      for (let step = 0; step <= 200; step++) {
        const t = step / 200;
        const u = 1 - t;
        const px = u ** 3 * x + 3 * u ** 2 * t * x1 + 3 * u * t ** 2 * x2 + t ** 3 * x3;
        const py = u ** 3 * y + 3 * u ** 2 * t * y1 + 3 * u * t ** 2 * y2 + t ** 3 * y3;
        radius = Math.max(radius, Math.hypot(inset + px * scale - 54, translateY + py * scale - 54));
      }
      x = x3;
      y = y3;
    } else {
      assert.equal(command, 'Z', 'Update the geometry check for new path commands');
    }
  }
}
assert(radius < 33, `Heart exceeds the 33dp safe-zone radius: ${radius}`);


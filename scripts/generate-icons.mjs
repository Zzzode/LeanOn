// Luminance contrast is an optical-centering proxy, not a bounding-box center.
// Monochrome uses alpha/filled area so the check is independent of theme tint.
const linear = Array.from({ length: 256 }, (_, value) => {
  const v = value / 255;
  return v <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4;
});
const centroidY = async (input, canvasDp, originDp, contrast) => {
  const { data, info } = await sharp(input).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  let weight = 0;
  let moment = 0;
  for (let i = 0; i < data.length; i += 4) {
    const alpha = data[i + 3] / 255;
    const luminance = linear[data[i]] * 0.2126 + linear[data[i + 1]] * 0.7152 + linear[data[i + 2]] * 0.0722;
    const w = alpha * (contrast ? 1 - luminance : 1);
    weight += w;
    moment += (Math.floor(i / 4 / info.width) + 0.5) * w;
  }
  assert(weight > 0, 'Expected a visible heart');
  return originDp + moment / weight / info.height * canvasDp;
};
const androidSvg = (colors) => Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="1080" height="1080" viewBox="0 0 108 108"><g transform="translate(${inset} ${translateY}) scale(${scale})">${heart.map((path, index) => `<path fill="${colors[index]}" d="${path}"/>`).join('')}</g></svg>`);
const centers = {
  color: await centroidY(androidSvg(['#58AB8D', '#218967']), 108, 0, true),
  monochrome: await centroidY(androidSvg(['#000000', '#000000']), 108, 0, false),
  ios: await centroidY(iosPng, 72, 18, true),
};
for (const [name, center] of Object.entries(centers)) {
  assert(Math.abs(center - 54) < 0.2, `${name} visual-weight center ${center}dp is off-center`);
}
